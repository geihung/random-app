# 2. 웹 페이지 제목 및 선택 위젯
st.title("직업별 계급 및 연봉 안내 프로그램")
choice = st.selectbox("원하는 직업을 선택하세요:", ["경찰", "군인", "공무원"])

st.divider()
st.subheader(f"[{choice} 계급 체계 및 예상 연봉]")

# 3. 가로 나열 출력 (한 줄에 4개씩 묶어서 카드 형태로 정렬)
ranks = job_data[choice]
chunk_size = 4

for i in range(0, len(ranks), chunk_size):
    chunk = ranks[i : i + chunk_size]
    cols = st.columns(chunk_size)  # 화면을 4칸으로 분할

    for idx, (rank, salary) in enumerate(chunk):
        with cols[idx]:
            # 마지막 계급이 아니면 오른쪽에 화살표 표시
            arrow = "  -> " if (i + idx < len(ranks) - 1) else ""
            st.markdown(f"**ㅣ{rank}ㅣ**{arrow}")
            st.caption(salary)  # 계급 바로 아래에 연봉 출력
