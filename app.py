def show_rank_system():
    # 1. 직업별 계급 및 연봉 데이터 (높은 계급 -> 낮은 계급 순, 대략적인 초봉 기준)
    job_data = {
        "경찰": [
            ("치안총감", "약 1억 4,000만 원"),
            ("치안정감", "약 1억 2,500만 원"),
            ("치안감", "약 1억 1,000만 원"),
            ("경무관", "약 9,500만 원"),
            ("총경", "약 8,200만 원"),
            ("경정", "약 6,800만 원"),
            ("경감", "약 5,600만 원"),
            ("경위", "약 4,600만 원"),
            ("경사", "약 4,100만 원"),
            ("경장", "약 3,700만 원"),
            ("순경", "약 3,400만 원"),
        ],
        "군인": [
            ("대장", "약 1억 5,000만 원"),
            ("중장", "약 1억 3,000만 원"),
            ("소장", "약 1억 1,500만 원"),
            ("준장", "약 9,800만 원"),
            ("대령", "약 8,500만 원"),
            ("중령", "약 7,200만 원"),
            ("소령", "약 6,000만 원"),
            ("대위", "약 4,800만 원"),
            ("중위", "약 3,800만 원"),
            ("소위", "약 3,500만 원"),
            ("원사", "약 6,500만 원"),
            ("상사", "약 5,200만 원"),
            ("중사", "약 4,000만 원"),
            ("하사", "약 3,300만 원"),
        ],
        "공무원": [
            ("1급(관리관)", "약 1억 1,000만 원"),
            ("2급(이사관)", "약 9,800만 원"),
            ("3급(부이사관)", "약 8,600만 원"),
            ("4급(서기관)", "약 7,400만 원"),
            ("5급(사무관)", "약 6,000만 원"),
            ("6급(주사)", "약 4,800만 원"),
            ("7급(주사보)", "약 4,000만 원"),
            ("8급(서기)", "약 3,400만 원"),
            ("9급(서기보)", "약 3,000만 원"),
        ],
    }

    print("==========================================")
    print("   직업별 계급 및 연봉 안내 프로그램")
    print("==========================================")

    # 2. 사용자 입력 받기
    choice = input("원하는 직업을 입력하세요 (경찰 / 군인 / 공무원): ").strip()

    # 3. 입력값 검증 및 출력
    if choice in job_data:
        print(f"\n[{choice} 계급 체계 및 예상 연봉]\n")
        ranks = job_data[choice]

        # 한 줄에 너무 길어지지 않도록 4개씩 끊어서 출력
        chunk_size = 4
        for i in range(0, len(ranks), chunk_size):
            chunk = ranks[i : i + chunk_size]

            rank_line = ""
            salary_line = ""

            for idx, (rank, salary) in enumerate(chunk):
                # 계급 포맷: ㅣ계급ㅣ
                rank_box = f"ㅣ{rank}ㅣ"

                # 다음 계급이 이어지면 화살표 추가
                if i + idx < len(ranks) - 1:
                    rank_box += " -> "

                rank_line += rank_box
                # 계급 박스의 길이에 맞춰 연봉을 아래에 정렬
                salary_line += f"{salary:<{len(rank_box) + 2}}"

            print(rank_line)
            print(salary_line)
            print()  # 줄 간격 띄우기

    else:
        print("\n잘못된 입력입니다. '경찰', '군인', '공무원' 중에서 정확히 입력해 주세요.")


# 프로그램 실행
if __name__ == "__main__":
    show_rank_system()
